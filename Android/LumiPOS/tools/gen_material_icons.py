D_RE = re.compile(r'\bd:\s*"([^"]+)"')

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Source: @mui/icons-material/{mui} (frontend/node_modules). Generated by
     tools/gen_material_icons.py - edit that script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24"
    android:tint="?attr/colorControlNormal">
{paths}
</vector>
"""

PATH_TEMPLATE = """    <path
        android:fillColor="@android:color/white"
        android:pathData="{d}" />"""


def extract_paths(mui_name):
    path = os.path.join(SRC_DIR, mui_name + ".js")
    if not os.path.exists(path):
        return None
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        text = fh.read()
    return D_RE.findall(text)


def main():
    if not os.path.isdir(SRC_DIR):
        raise SystemExit("icon package not found: %s" % SRC_DIR)

    os.makedirs(OUT_DIR, exist_ok=True)
    written, skipped, failed = 0, 0, []

    for mui, android in sorted(ICONS.items()):
        out = os.path.join(OUT_DIR, android + ".xml")
        if os.path.exists(out):
            skipped += 1
            continue

        paths = extract_paths(mui)
        if not paths:
            failed.append((mui, "no path data found"))
            continue

        body = "\n".join(PATH_TEMPLATE.format(d=d) for d in paths)
        with open(out, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(TEMPLATE.format(mui=mui, paths=body))
        written += 1
        print("  + %-28s <- %s (%d path%s)" % (android + ".xml", mui, len(paths), "" if len(paths) == 1 else "s"))

    print()
    print("written: %d | already present: %d | failed: %d" % (written, skipped, len(failed)))
    for mui, why in failed:
        print("  !! %s: %s" % (mui, why))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
