package com.bms.config;

import com.bms.entity.User;
import jakarta.persistence.Column;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.boot.DefaultApplicationArguments;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.sql.Connection;
import java.sql.SQLException;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertAll;
import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * N2: the user-identity columns introduced by the auth hardening must not break
 * shops that upgrade into them.
 *
 * <p>An existing database has no {@code token_version}, {@code username_normalized}
 * or {@code email_normalized} columns, and it can already hold both {@code admin}
 * and {@code Admin} because case-sensitive uniqueness accepted them. Backfilling
 * the normalized key onto every row then collides with the new unique index, so
 * startup would abort before the shop can log in.
 *
 * <p>These tests build that legacy schema by hand and replay the upgrade.
 */
class UserAccountUpgradeMigrationTest {

    private static final String LEGACY_USERS = """
            create table users (
                id bigint generated by default as identity primary key,
                username varchar(255) not null unique,
                email varchar(255) not null unique,
                password varchar(255) not null,
                first_name varchar(255) not null,
                last_name varchar(255) not null,
                phone varchar(255),
                is_active boolean not null default true,
                created_at timestamp not null default current_timestamp
            )""";

    private static final String LEGACY_AUDIT_LOGS = """
            create table audit_logs (
                id bigint generated by default as identity primary key,
                user_id bigint,
                action varchar(255) not null,
                description varchar(1000),
                entity_type varchar(255),
                entity_id bigint,
                old_values varchar(5000),
                new_values varchar(5000),
                ip_address varchar(255),
                user_agent varchar(255),
                timestamp timestamp not null
            )""";

    private static final String LEGACY_COUNT_SHEETS = """
            create table count_sheets (
                id bigint generated by default as identity primary key,
                sync_key varchar(255)
            )""";

    /** Tables the startup migration adds columns to, without those columns. */
    private static final String[] LEGACY_ID_ONLY_TABLES = {
            "customers", "orders", "expenses", "count_sheet_items",
            "sale_returns", "ar_payments", "stock_movements"
    };

    private Connection keepAliveConnection;
    private JdbcTemplate jdbc;
    private AccountingSchemaMigration migration;

    @BeforeEach
    void openLegacyDatabase() throws SQLException {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:users_upgrade_" + UUID.randomUUID(), "sa", "");
        dataSource.setDriverClassName("org.h2.Driver");
        // H2 drops an in-memory database when its last connection closes, and the
        // migration opens a connection per statement, so hold the session open.
        keepAliveConnection = dataSource.getConnection();
        jdbc = new JdbcTemplate(dataSource);
        migration = new AccountingSchemaMigration(dataSource);

        jdbc.execute(LEGACY_USERS);
        jdbc.execute(LEGACY_AUDIT_LOGS);
        jdbc.execute(LEGACY_COUNT_SHEETS);
        for (String table : LEGACY_ID_ONLY_TABLES) {
            jdbc.execute("create table " + table + " (id bigint generated by default as identity primary key)");
        }
    }

    @AfterEach
    void closeLegacyDatabase() throws SQLException {
        if (keepAliveConnection != null) {
            keepAliveConnection.close();
        }
    }

    private void seedThreeLegacyUsers() {
        jdbc.update("insert into users (id, username, email, password, first_name, last_name, is_active)"
                + " values (1, 'admin', 'Shop@Example.com', 'hash1', 'Ada', 'Min', true)");
        jdbc.update("insert into users (id, username, email, password, first_name, last_name, is_active)"
                + " values (2, 'Admin', 'shop@example.com', 'hash2', 'Bob', 'Ob', true)");
        jdbc.update("insert into users (id, username, email, password, first_name, last_name, is_active)"
                + " values (3, 'cashier', 'cash@example.com', 'hash3', 'Cy', 'Er', true)");
    }

    @Test
    void anOldBackupSettingsTableGainsTheScheduleRetentionAndAnchorColumns() throws Exception {
        seedThreeLegacyUsers();
        // The table as it stood before the backup hour was stored, before the
        // shop could say how many nights of backups to keep, and before a
        // monthly run remembered which day of the month it belongs to.
        jdbc.execute("create table backup_settings (id bigint generated by default as identity"
                + " primary key, is_enabled boolean not null, frequency varchar(255) not null)");
        jdbc.execute("insert into backup_settings (is_enabled, frequency) values (true, 'DAILY')");

        migration.run(new DefaultApplicationArguments());

        assertEquals(1, jdbc.queryForObject(
                "SELECT COUNT(*) FROM backup_settings WHERE retention_count = 30", Integer.class),
                "the row that is already there gets the retention the new code reads");
        assertEquals(1, jdbc.queryForObject(
                "SELECT COUNT(*) FROM backup_settings WHERE scheduled_time IS NULL", Integer.class),
                "an old schedule is not guessed at, it is simply not set");
        assertEquals(1, jdbc.queryForObject(
                "SELECT COUNT(*) FROM backup_settings WHERE anchor_day_of_month IS NULL", Integer.class),
                "an old row keeps its own planned day instead of an invented anchor");
    }

    @Test
    void startupMigrationOnALegacyDatabaseFinishesWithoutThrowing() {
        seedThreeLegacyUsers();

        assertDoesNotThrow(() -> migration.run(new DefaultApplicationArguments()));

        assertEquals(0, jdbc.queryForObject(
                "SELECT COUNT(*) FROM users WHERE username_normalized IS NULL OR email_normalized IS NULL"
                        + " OR token_version IS NULL", Integer.class),
                "every legacy row must end the upgrade with a normalized key and a token version");
        assertEquals(3, jdbc.queryForObject("SELECT COUNT(*) FROM users WHERE token_version = 0", Integer.class),
                "the backfilled token version is 0, matching the entity default");
    }

    @Test
    void caseDuplicateUsernameKeepsTheLowestIdAndReleasesTheLaterAccount() {
        seedThreeLegacyUsers();

        migration.migrateUserIdentity();

        assertAll("released duplicate",
                () -> assertEquals("admin", normalized("username_normalized", 1L)),
                () -> assertEquals("admin#dup_2", normalized("username_normalized", 2L)),
                () -> assertEquals("cashier", normalized("username_normalized", 3L)),
                () -> assertEquals(Boolean.TRUE, jdbc.queryForObject(
                        "SELECT is_active FROM users WHERE id = 1", Boolean.class)),
                () -> assertEquals(Boolean.FALSE, jdbc.queryForObject(
                        "SELECT is_active FROM users WHERE id = 2", Boolean.class),
                        "the duplicate username is deactivated so login cannot reach two accounts"),
                () -> assertEquals("admin", jdbc.queryForObject(
                        "SELECT username FROM users WHERE id = 1", String.class)),
                () -> assertEquals("Admin", jdbc.queryForObject(
                        "SELECT username FROM users WHERE id = 2", String.class),
                        "releasing a key must never rewrite the display username or delete the row"));
    }

    @Test
    void caseDuplicateEmailIsReleasedTooAndEachReleaseIsAudited() {
        seedThreeLegacyUsers();

        migration.migrateUserIdentity();

        assertAll("duplicate release audit",
                () -> assertEquals("shop@example.com", normalized("email_normalized", 1L)),
                () -> assertEquals("shop@example.com#dup_2", normalized("email_normalized", 2L)),
                () -> assertEquals(2, jdbc.queryForObject(
                        "SELECT COUNT(*) FROM audit_logs WHERE action = 'USER_DUPLICATE_DETECTED'", Integer.class),
                        "one row for the username key and one for the email key"),
                () -> assertEquals(2, jdbc.queryForObject(
                        "SELECT COUNT(*) FROM audit_logs WHERE action = 'USER_DUPLICATE_DETECTED'"
                                + " AND entity_id = 2 AND user_id = 2", Integer.class),
                        "each row must name the account that was released"),
                () -> assertEquals("User", jdbc.queryForObject(
                        "SELECT entity_type FROM audit_logs WHERE action = 'USER_DUPLICATE_DETECTED'"
                                + " LIMIT 1", String.class)));
        assertTrue(jdbc.queryForList(
                "SELECT description FROM audit_logs WHERE action = 'USER_DUPLICATE_DETECTED'", String.class)
                .stream().allMatch(text -> text.length() <= 1000),
                "the audit description must fit its column");
    }

    @Test
    void upgradeIsRepeatableAndLeavesTheDataAloneTheSecondTime() {
        seedThreeLegacyUsers();

        migration.migrateUserIdentity();
        int rowsAfterFirstRun = jdbc.queryForObject("SELECT COUNT(*) FROM users", Integer.class);
        int auditAfterFirstRun = jdbc.queryForObject("SELECT COUNT(*) FROM audit_logs", Integer.class);

        assertDoesNotThrow(() -> migration.migrateUserIdentity());

        assertAll("second run",
                () -> assertEquals(rowsAfterFirstRun, jdbc.queryForObject("SELECT COUNT(*) FROM users", Integer.class)),
                () -> assertEquals(auditAfterFirstRun,
                        jdbc.queryForObject("SELECT COUNT(*) FROM audit_logs", Integer.class),
                        "a repeat upgrade finds nothing left to release"),
                () -> assertEquals(0, migration.normalizeAndDedupeUserAccounts()),
                () -> assertEquals("admin#dup_2", normalized("username_normalized", 2L),
                        "released keys must not be folded back onto the kept key"));
    }

    @Test
    void uniqueIndexesExistAfterTheUpgradeAndRejectANewDuplicate() {
        seedThreeLegacyUsers();

        migration.migrateUserIdentity();

        assertThrows(DataIntegrityViolationException.class,
                () -> jdbc.update("insert into users (username, email, password, first_name, last_name,"
                                + " is_active, username_normalized, email_normalized, token_version)"
                                + " values ('ADMIN2', 'other@example.com', 'hash', 'New', 'User', true,"
                                + " 'admin', 'other@example.com', 0)"),
                "the unique index must make a third admin impossible to insert");
        assertTrue(jdbc.queryForList("SELECT DISTINCT INDEX_NAME FROM INFORMATION_SCHEMA.INDEXES"
                        + " WHERE TABLE_NAME = 'USERS'", String.class)
                .contains("UQ_USERS_USERNAME_NORMALIZED"));
    }

    @Test
    void aFreshInstallWithNoDuplicatesHasNothingToDedupe() {
        // A new database already has the columns (Hibernate created them) and the
        // app writes the keys, so the startup step must be a no-op there.
        jdbc.execute("alter table users add column token_version integer");
        jdbc.execute("alter table users add column username_normalized varchar(255)");
        jdbc.execute("alter table users add column email_normalized varchar(255)");
        jdbc.update("insert into users (id, username, email, password, first_name, last_name, is_active,"
                + " username_normalized, email_normalized, token_version)"
                + " values (1, 'admin', 'shop@example.com', 'hash1', 'Ada', 'Min', true,"
                + " 'admin', 'shop@example.com', 0)");
        jdbc.update("insert into users (id, username, email, password, first_name, last_name, is_active,"
                + " username_normalized, email_normalized, token_version)"
                + " values (3, 'cashier', 'cash@example.com', 'hash3', 'Cy', 'Er', true,"
                + " 'cashier', 'cash@example.com', 0)");

        assertEquals(0, migration.normalizeAndDedupeUserAccounts());
        assertEquals(0, jdbc.queryForObject(
                "SELECT COUNT(*) FROM audit_logs WHERE action = 'USER_DUPLICATE_DETECTED'", Integer.class));
    }

    @Test
    void tokenVersionColumnStaysUpgradeableByEveryDatabase() throws NoSuchFieldException {
        // A NOT NULL column with no default cannot be ALTERed onto an existing
        // SQLite table, so the entity must keep it nullable and let the
        // migration backfill it instead.
        Column column = User.class.getDeclaredField("tokenVersion").getAnnotation(Column.class);
        assertTrue(column.nullable(), "users.token_version must stay nullable for the upgrade to work");
        assertEquals("token_version", column.name());
    }

    private String normalized(String column, Long id) {
        return jdbc.queryForObject("SELECT " + column + " FROM users WHERE id = ?", String.class, id);
    }
}
